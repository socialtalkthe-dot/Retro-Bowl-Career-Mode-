const COLD_STATES = new Set([
  'Alaska', 'Colorado', 'Connecticut', 'Idaho', 'Illinois', 'Indiana', 'Iowa', 'Maine',
  'Massachusetts', 'Michigan', 'Minnesota', 'Montana', 'Nebraska', 'New Hampshire',
  'New Jersey', 'New York', 'North Dakota', 'Ohio', 'Pennsylvania', 'Rhode Island',
  'South Dakota', 'Utah', 'Vermont', 'Wisconsin', 'Wyoming',
]);

export const ALL_HS_BY_STATE: Record<string, HsSpec[]> = Object.fromEntries(
  Object.entries(HS_BY_STATE).map(([state, baseSpecs]) => {
    const seen = new Set<string>();
    const combined: HsSpec[] = [];
    for (const spec of [...baseSpecs, ...(HS_EXTRA_MERGED[state] ?? [])]) {
      const key = spec[0].toLowerCase().replace(/[^a-z0-9]/g, '');
      if (seen.has(key)) continue;
      seen.add(key);
      combined.push(spec);
    }
    return [state, combined];
  })
);

export const HIGH_SCHOOL_TEAMS: LeagueTeam[] = Object.entries(ALL_HS_BY_STATE).flatMap(
  ([state, specs]) =>
    specs.map((spec, idx) => {
      const [name, mascot, city, division, primary, secondary, helmet, offense, defense] = spec;
      const slug = `${state}_${name}`.toLowerCase().replace(/[^a-z0-9]+/g, '_');
      const shortName = name
        .replace(/'/g, '')
        .split(/[\s-]+/)
        .map((w) => w[0])
        .join('')
        .slice(0, 3)
        .toUpperCase();
      return {
        id: `hs_${slug}`,
        name: `${name} ${mascot}`,
        shortName: shortName.length >= 2 ? shortName : name.replace(/'/g, '').slice(0, 3).toUpperCase(),
        mascot,
        city,
        state,
        conference: `${state} State`,
        division,
        era: 'HIGH_SCHOOL',
        offense,
        defense,
        prestige: Math.min(5, Math.max(2, Math.round((offense + defense) / 4))),
        roof: 0,
        rainfall: state === 'Washington' || state === 'Oregon' || state === 'Hawaii' ? 48 : state === 'Arizona' || state === 'Nevada' || state === 'New Mexico' ? 8 : 28,
        snowfall: COLD_STATES.has(state) ? 35 : 0,
        uniforms: makeHsUniforms(primary, secondary, helmet),
        rivalId: specs[(idx + 1) % specs.length]
          ? `hs_${`${state}_${specs[(idx + 1) % specs.length][0]}`.toLowerCase().replace(/[^a-z0-9]+/g, '_')}`
          : undefined,
        stadium: `${name} Memorial Stadium`,
      };
    })
);
